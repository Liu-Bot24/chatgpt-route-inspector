const dictionaries: Record<UiLanguage, Record<TranslationKey, string>> = { zh, en };
export const TRANSLATION_KEYS = Object.freeze(Object.keys(zh) as TranslationKey[]);

export function t(language: UiLanguage, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  let value = dictionaries[language][key] ?? en[key] ?? key;
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{{${name}}}`, String(replacement));
  }
  return value;
}

export function applyStaticTranslations(language: UiLanguage, root: Document | ShadowRoot | HTMLElement = document): void {
  const documentRef = root instanceof Document ? root : root.ownerDocument;
  documentRef.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n as TranslationKey | undefined;
    if (key) element.textContent = t(language, key);
  });
  for (const [attribute, dataName] of [['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle']] as const) {
    root.querySelectorAll<HTMLElement>(`[data-${dataName.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`)}]`).forEach((element) => {
      const key = element.dataset[dataName] as TranslationKey | undefined;
      if (key) element.setAttribute(attribute, t(language, key));
    });
  }
  root.querySelectorAll<HTMLButtonElement>('[data-language]').forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

export function bindLanguageSwitch(handler: (language: UiLanguage) => void | Promise<void>, root: Document | HTMLElement = document): void {
  root.querySelectorAll<HTMLButtonElement>('[data-language]').forEach((button) => {
    button.addEventListener('click', () => {
      const language = button.dataset.language;
      if (language === 'zh' || language === 'en') void handler(language);
    });
  });
}

